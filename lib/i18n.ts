export const LOCALES = ["fr", "en", "es"] as const;
export type Locale = (typeof LOCALES)[number];

export function isLocale(value: string | undefined): value is Locale {
  return value === "fr" || value === "en" || value === "es";
}

export function detectLocale(acceptLanguage: string | null | undefined, countryCode?: string | null): Locale {
  const preferences = (acceptLanguage ?? "")
    .split(",")
    .map((part) => {
      const [tag, quality] = part.trim().split(/;\s*q=/i);
      return { language: tag.toLowerCase().split("-")[0], quality: Number(quality ?? 1) };
    })
    .filter((entry) => Number.isFinite(entry.quality) && entry.quality > 0 && entry.quality <= 1)
    .sort((a, b) => b.quality - a.quality);

  for (const preference of preferences) {
    if (preference.language === "fr" || preference.language === "en" || preference.language === "es") {
      return preference.language;
    }
  }
  return countryCode?.toUpperCase() === "ES" ? "es" : "fr";
}

